// 获取所有关键词并去重
export function getAllKeywords(matrix: KeywordMatrix): string {
  const all = [
    ...matrix.core,
    ...matrix.grade,
    ...matrix.subject,
    ...matrix.function,
    ...matrix.format,
    ...matrix.difficulty,
    ...matrix.user,
    ...matrix.action,
    ...matrix.mobile,
    ...matrix.combined
  ];
  return [...new Set(all)].join(',');
}
