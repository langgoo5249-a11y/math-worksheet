export interface VersionContent {
  textbook: TextbookVersion;
  profile: VersionProfile;
  guides: GradeGuide[];
}

/** 取某个教材版本的完整聚合页内容 */
export function getVersionContent(id: string): VersionContent | undefined {
  const textbook = getTextbook(id);
  if (!textbook) return undefined;
  const profile = VERSION_PROFILES[id];
  const guides = GRADE_GUIDE_MAP[id];
  if (!profile || !guides) return undefined;
  return { textbook, profile, guides };
}

/** 参与聚合的版本 id 列表（与 TEXTBOOKS 顺序一致）*/
export function getVersionIds(): string[] {
  return TEXTBOOKS.map((t) => t.id);
}
